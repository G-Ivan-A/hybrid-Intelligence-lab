def field_value(line):
    """Span (start, end) of the value of a labelled field, card text, footer sources or decision item on a v4 line."""
    for pattern in (r"^- Карточка: \d\d · [^—]+ — (.*)$", r"^Источники: (.*?) · \(Telegram\)", r"^- \[x\] (.*)$",
                    r"^- [А-ЯЁа-яё ]+: (.*)$", r"^\d+\. (.*)$", r"^(\|.*\|)$"):
        match = re.match(pattern, line)
        if match:
            return match.span(1)
    raise SystemExit(f"no field on line: {line[:80]!r}")


def resolve(lines):
    """Concrete (line, old, new, reason) rows: FIELD and APPEND become the quoted value of the field."""
    rows = []
    for n, old, new, reason in EDITS:
        line = lines[n - 1]
        if old in (FIELD, APPEND):
            start, end = field_value(line)
            value = line[start:end]
            old, new = value, value + new if old == APPEND else new
        if line.count(old) != 1:
            raise SystemExit(f"L{n}: old fragment occurs {line.count(old)} times: {old[:80]!r}")
        rows.append((n, old, new, reason))
    return rows


def apply(lines, rows):
    """Apply rows to v4 lines right to left within each line; fragments of one line must not overlap."""
    result = list(lines)
    by_line = {}
    for n, old, new, _ in rows:
        by_line.setdefault(n, []).append((lines[n - 1].index(old), old, new))
    for n, edits in by_line.items():
        edits.sort()
        for (a, old_a, _), (b, _, _) in zip(edits, edits[1:]):
            if a + len(old_a) > b:
                raise SystemExit(f"L{n}: overlapping fragments")
        text = lines[n - 1]
        for start, old, new in reversed(edits):
            text = text[:start] + new + text[start + len(old):]
        result[n - 1] = text
    return result


def apply_prompt_tail(lines):
    count = sum(line.count(PROMPT_TAIL_OLD) for line in lines)
    if count != PROMPTS:
        raise SystemExit(f"prompt tail occurs {count} times, expected {PROMPTS}")
    return [line.replace(PROMPT_TAIL_OLD, PROMPT_TAIL_NEW) for line in lines]


def locate(lines, n):
    """Slide number and field name of v4 line n; slide None for service lines outside the slides."""
    slide, field, sources = None, None, False
    for i, line in enumerate(lines[:n], 1):
        if line.startswith("## Источники и уровень опоры"):
            sources = True
        match = re.match(r"^### Слайд (\d+)\. ", line)
        if match and not sources:
            slide, field = int(match[1]), "### Заголовок слайда"
        match = re.match(r"^\*\*\[([A-Z_]+)\]\*\*", line)
        if match:
            field = f"[{match[1]}]"
    if sources or slide is None:
        return None, None
    line = lines[n - 1]
    match = re.match(r"^- Карточка: (\d\d) · ", line) or re.match(r"^- ([А-ЯЁа-яё ]+): ", line)
    if field == "[SLIDE_TEXT]" and match:
        field += f" · {'Карточка ' + match[1] if match[1].isdigit() else match[1]}"
    return slide, field


SERVICE_SECTIONS = ((1, "frontmatter"), (16, "Введение файла"), (28, "Как читать"), (103, "Промпт для генерации в Gamma"),
                    (662, "Источники и уровень опоры"), (688, "Гейт-проверка"), (703, "Решения исполнителя"))


def service_section(n):
    return [name for start, name in SERVICE_SECTIONS if start <= n][-1]


def cell(text):
    return text.replace("|", "\\|")


def table(lines, rows):
    head = "| № | Слайд | Поле | Было (v4, дословно) | Стало (v5) | Обоснование |\n| --- | --- | --- | --- | --- | --- |\n"
    slide_rows, service_rows = [], []
    for n, old, new, reason in rows:
        slide, field = locate(lines, n)
        target = slide_rows if slide else service_rows
        target.append((n, slide or "—", field or service_section(n), old, new, reason))
    slide_rows.sort(key=lambda row: (row[1], row[0]))
    out = ["Ниже — все точечные замены. Номер строки «Было» ведёт на эту строку колоды v4 в коммите `f3af657`. "
           "Строка G-01 — общая замена в хвосте всех 27 промптов изображений.\n",
           "### Слайды\n", head.rstrip("\n")]
    out.append(f"| G-01 | 1–27 | [IMAGE_PROMPT] | [v4:L149]({PERMALINK}149) «{cell(PROMPT_TAIL_OLD.strip())}» | "
               f"«{cell(PROMPT_TAIL_NEW.strip())}» | {cell(R_IMAGE)} Замена — в каждом из 27 промптов; палитра, золотой акцент "
               "#B89B5E, вертикаль 1:2.4 и «No text» сохранены. |")
    for i, (n, slide, field, old, new, reason) in enumerate(slide_rows, 1):
        out.append(f"| V5-{i:03d} | {slide} | {field} | [v4:L{n}]({PERMALINK}{n}) «{cell(old)}» | «{cell(new)}» | {cell(reason)} |")
    out += ["", "### Служебные разделы файла\n",
            "Эти строки стоят вне слайдов: frontmatter, «Как читать», промпт Gamma, таблица источников, гейт-проверка и решения исполнителя.\n",
            head.rstrip("\n")]
    for i, (n, _, section_name, old, new, reason) in enumerate(sorted(service_rows), 1):
        out.append(f"| S-{i:03d} | — | {section_name} | [v4:L{n}]({PERMALINK}{n}) «{cell(old)}» | «{cell(new)}» | {cell(reason)} |")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", type=Path, help="write the deck v4 with every edit applied (v5 preview) to this path")
    parser.add_argument("--no-rfc", action="store_true", help="do not rewrite section 2 of the RFC")
    args = parser.parse_args()
    lines = DECK.read_text(encoding="utf-8").split("\n")
    rows = resolve(lines)
    v5 = apply_prompt_tail(apply(lines, rows))
    if args.preview:
        args.preview.write_text("\n".join(v5), encoding="utf-8")
    if not args.no_rfc:
        text = RFC.read_text(encoding="utf-8")
        head, rest = text.split("## 2. Таблица замен (Diffs)\n", 1)
        _, tail = rest.split("\n## 3. ", 1)
        RFC.write_text(f"{head}## 2. Таблица замен (Diffs)\n\n{table(lines, rows)}\n## 3. {tail}", encoding="utf-8")
    print(f"PASS: {len(rows)} point edits and the prompt tail G-01 applied to {DECK.name}")


if __name__ == "__main__":
    main()
