def status(v=0, p=0, c=0, q=0, extra=""):
    """«Статусы проверки: …» in the order of the taxonomy, with the context phrase for PARTIAL or CONFLICT."""
    parts = [f"{n} {name}" for n, name in ((v, "VERIFIED"), (p, "PARTIAL"), (c, "CONFLICT")) if n]
    parts += [f"{q} «?»"] if q else []
    line = "Статусы проверки: " + ", ".join(parts) + extra + "."
    return line + (" " + CONTEXT if p or c or "PARTIAL" in extra else "")


